export type I18nKey = keyof typeof dict.zh;

let current: Lang = readStored();

function readStored(): Lang {
  try {
    const v = localStorage.getItem(LS_KEY);
    return v === 'en' ? 'en' : 'zh';
  } catch { return 'zh'; }
}

export function getLang(): Lang { return current; }

export function setLang(lang: Lang, opts?: { fromDsh?: boolean }) {
  if (lang !== 'zh' && lang !== 'en') return;
  current = lang;
  try { localStorage.setItem(LS_KEY, lang); } catch { /* noop */ }
  try { window.dispatchEvent(new CustomEvent('rl-lang-changed', { detail: lang })); } catch { /* noop */ }
  // [v181b] 语言桥正向：软件切语言 → 同步 DSH 界面语言（DSH 页内切换走 fromDsh，不回写防循环）
  if (!opts?.fromDsh) {
    try {
      const dl = (window as any).dshLocale;
      if (dl && dl.sync) dl.sync(lang).catch((e: unknown) => { console.warn('[i18n] DSH locale sync fail:', e); });
      else console.warn('[i18n] window.dshLocale unavailable — 语言桥未加载');
    } catch { /* noop */ }
  }
}

export function t(key: I18nKey | string): string {
  const d = dict[current] as Record<string, string>;
  if (d && Object.prototype.hasOwnProperty.call(d, key)) return d[key];
  const z = dict.zh as Record<string, string>;
  if (Object.prototype.hasOwnProperty.call(z, key)) return z[key];
  return String(key);
}

// console.html（非 React）经 window 取当前语言与文案
if (typeof window !== 'undefined') {
  (window as any).__i18n = { getLang, setLang, t };
}
